"""
Экономика WB DEXI по артикулам — из скачанных продаж.

Считает по каждому артикулу: продано, выручка, средняя цена, доля в общей
выручке. Плюс сверка с Ozon — какие товары продаются на обеих площадках,
а какие только на одной.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

ПАПКА = Path(r"D:\файлы Гермес\04_Маркетплейсы")
ВЫГРУЗКИ = ПАПКА / "03_Выгрузки"

вб = json.loads((ВЫГРУЗКИ / "WB_продажи.json").read_text(encoding="utf-8"))
озон = json.loads((ВЫГРУЗКИ / "экономика_Ozon.json").read_text(encoding="utf-8"))

# ---------- WB по артикулам ----------
арт = defaultdict(lambda: {"шт": 0, "выручка": 0.0, "цены": [],
                           "товар": "", "категория": "", "бренд": "",
                           "nmId": None, "месяцы": set()})
for з in вб:
    к = з.get("supplierArticle") or "?"
    а = арт[к]
    а["шт"] += 1
    # forPay — сколько реально получит продавец; priceWithDisc — цена покупателя
    а["выручка"] += float(з.get("forPay") or 0)
    а["цены"].append(float(з.get("priceWithDisc") or 0))
    а["товар"] = а["товар"] or (з.get("subject") or "")
    а["категория"] = а["категория"] or (з.get("category") or "")
    а["бренд"] = а["бренд"] or (з.get("brand") or "")
    а["nmId"] = а["nmId"] or з.get("nmId")
    if з.get("date"):
        а["месяцы"].add(з["date"][:7])

всего_вб = sum(а["выручка"] for а in арт.values())
всего_шт = sum(а["шт"] for а in арт.values())

print("=" * 104)
print("WB DEXI — ЭКОНОМИКА ПО АРТИКУЛАМ (по факту продаж)")
print("=" * 104)
print(f"\nВсего: {всего_шт} продаж, {всего_вб:,.0f} ₽, {len(арт)} артикулов")
print(f"Период: {min(min(а['месяцы']) for а in арт.values() if а['месяцы'])} — "
      f"{max(max(а['месяцы']) for а in арт.values() if а['месяцы'])}")

print(f"\n{'артикул':<30}{'шт':>5}{'выручка':>12}{'сред.цена':>11}"
      f"{'доля':>7}  товар")
print("-" * 104)
for к, а in sorted(арт.items(), key=lambda п: -п[1]["выручка"]):
    ср = sum(а["цены"]) / len(а["цены"]) if а["цены"] else 0
    доля = а["выручка"] / всего_вб * 100
    print(f"{к[:30]:<30}{а['шт']:>5}{а['выручка']:>12,.0f}{ср:>11,.0f}"
          f"{доля:>6.1f}%  {а['товар'][:34]}")

# ---------- Ozon по товарам ----------
МУСОР = ("Заказ №", "Электронная услуга", "Услуга", "Доставка", "Штраф",
         "Компенсация", "Корректировка")


def это_товар(н):
    н = (н or "").strip()
    if not н or н == "(без названия)":
        return False
    return not any(н.startswith(м) for м in МУСОР)


оз_товар = defaultdict(lambda: {"шт": 0, "выручка": 0.0})
for с in озон:
    if not это_товар(с.get("товар")):
        continue
    выр = float(с.get("продажи_руб") or 0)
    if выр <= 0:
        continue
    оз_товар[с["товар"]]["выручка"] += выр
    оз_товар[с["товар"]]["шт"] += int(с.get("продажи_шт") or 0)


def ключ(н: str) -> str:
    """Грубое сопоставление названий WB и Ozon по значимым словам."""
    н = (н or "").lower()
    н = re.sub(r"[^а-яёa-z0-9 ]", " ", н)
    слова = [с for с in н.split() if len(с) > 3]
    return " ".join(sorted(set(слова)))


print()
print("=" * 104)
print("СВЕРКА WB ↔ OZON — что продаётся на обеих площадках")
print("=" * 104)

оз_по_словам = defaultdict(lambda: {"выручка": 0.0, "шт": 0, "имя": ""})
for имя, д in оз_товар.items():
    оз_по_словам[ключ(имя)]["выручка"] += д["выручка"]
    оз_по_словам[ключ(имя)]["шт"] += д["шт"]
    оз_по_словам[ключ(имя)]["имя"] = имя

совпало, только_вб = [], []
for к, а in арт.items():
    кл = ключ(а["товар"])
    if кл in оз_по_словам and оз_по_словам[кл]["выручка"] > 0:
        о = оз_по_словам[кл]
        совпало.append((к, а, о))
    else:
        только_вб.append((к, а))

print(f"\nНа ОБЕИХ площадках: {len(совпало)} категорий товара")
print(f"\n{'WB товар':<34}{'WB руб':>10}{'Ozon руб':>12}{'во сколько':>13}")
print("-" * 104)
for к, а, о in sorted(совпало, key=lambda п: -п[2]["выручка"]):
    отн = о["выручка"] / а["выручка"] if а["выручка"] else 0
    print(f"{а['товар'][:34]:<34}{а['выручка']:>10,.0f}"
          f"{о['выручка']:>12,.0f}{отн:>12.1f}x")

print(f"\nТОЛЬКО на WB ({len(только_вб)}):")
for к, а in sorted(только_вб, key=lambda п: -п[1]["выручка"])[:12]:
    print(f"  {а['выручка']:>10,.0f} ₽  {а['шт']:>4} шт  {а['товар'][:50]}")

print(f"""
ВЫВОД
  WB продал на {всего_вб:,.0f} ₽, Ozon — на {sum(д['выручка'] for д in оз_товар.values()):,.0f} ₽
  Отношение: {sum(д['выручка'] for д in оз_товар.values()) / всего_вб:.0f} : 1 в пользу Ozon
""")

(ВЫГРУЗКИ / "WB_экономика_артикулы.json").write_text(
    json.dumps({к: {**а, "месяцы": sorted(а["месяцы"]),
                    "средняя_цена": round(sum(а["цены"]) / len(а["цены"]), 2)
                    if а["цены"] else 0}
                for к, а in арт.items()},
               ensure_ascii=False, indent=1), encoding="utf-8")
print("Сохранено: 03_Выгрузки\\WB_экономика_артикулы.json")
