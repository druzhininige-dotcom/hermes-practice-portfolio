# Мягкая подача утром (выбран вариант 3 — «тёплый, бодрый»).
# Утро не должно быть командным — ребёнок просыпается спокойно.
НАСТРОЙКИ_УТРО = {"rate": "-12%", "pitch": "-1Hz"}
НАСТРОЙКИ_ВЕЧЕР = {"rate": "-18%", "pitch": "-2Hz"}   # вечером ещё мягче

ДНИ = ["понедельник", "вторник", "среда", "четверг",
       "пятница", "суббота", "воскресенье"]


def сейчас():
    """Время берём у Windows — TZ=Asia/Vladivostok в Python врёт."""
    try:
        out = subprocess.check_output(
            ["powershell", "-Command",
             "Get-Date -Format 'yyyy-MM-dd HH:mm:ss dddd'"],
            stderr=subprocess.DEVNULL, timeout=15
        ).decode("utf-8", errors="replace").strip()
        дата, время, = out.split(" ")[0], out.split(" ")[1]
        дн = out.split(" ")[2] if len(out.split(" ")) > 2 else ""
        y, m, d = [int(x) for x in дата.split("-")]
        чч, мм, сс = [int(x) for x in время.split(":")]
        return datetime.datetime(y, m, d, чч, мм, сс), дн
    except Exception:
        # запасной вариант, если PowerShell недоступен
        return datetime.datetime.now(), ""


def загрузить():
    with open(ФАЙЛ_РАСПИСАНИЯ, encoding="utf-8") as f:
        return json.load(f)


def день_недели(дт=None):
    """0=понедельник ... 6=воскресенье"""
    дт = дт or сейчас()[0]
    return дт.weekday()


def уроки_на(день_индекс, данные):
    ключ = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"][день_индекс]
    return данные["уроки"].get(ключ, [])


def расписание_текстом(день_индекс, данные, кратко=False, завтра=False):
    """Текст для озвучки/вывода.

    завтра=True — меняет «Сегодня» на «Завтра».
    """
    название = данные["дни"][день_индекс]
    уроки = уроки_на(день_индекс, данные)
    вводное = "Завтра" if завтра else "Сегодня"

    if not уроки:
        return f"{вводное} {название}. Уроков нет — выходной!"

    строки = [f"{вводное} {название}, {len(уроки)} "
              f"{'урок' if len(уроки) == 1 else 'уроков'}."]

    if кратко:
        строки.append("Уроки: " + ", ".join(
            f"{i+1}. {у['предмет']}" for i, у in enumerate(уроки)) + ".")
    else:
        for i, у in enumerate(уроки, 1):
            кабинет = (у.get("кабинет") or "").strip()
            if кабинет:
                строки.append(f"{i}. {у['предмет']}, кабинет {кабинет}.")
            else:
                строки.append(f"{i}. {у['предмет']}.")

    # что взять с собой (собираем уникально)
    взять = []
    for у in уроки:
        for в in (у.get("взять") or "").split(","):
            в = в.strip()
            if в and в.lower() not in [x.lower() for x in взять]:
                взять.append(в)
    if взять:
        строки.append("Не забыть: " + ", ".join(взять) + ".")

    return " ".join(строки)


def первое_время(день_индекс, данные):
    """Время начала первого урока (или первого звонка)."""
    уроки = уроки_на(день_индекс, данные)
    if not уроки:
        return None
    запасное = None
    начало_уроков = данные.get("начало_уроков")
    if начало_уроков:
        запасное = начало_уроков[0]
    else:
        звонки = данные.get("звонки")
        if isinstance(звонки, dict) and "1" in звонки:
            запасное = звонки["1"].get("начало")
        elif isinstance(звонки, list) and звонки:
            запасное = звонки[0]
    return уроки[0].get("начало", запасное)


def подъём_текст(данные, дт=None, имя=None):
    """Мягкий утренний текст (вариант 3 — «тёплый, бодрый»).

    Никакого командного «Подъём!» — ребёнок просыпается спокойно.
    """
    дт, _ = сейчас() if дт is None else (дт, "")
    имя = имя or данные.get("имя_ребёнка", "")
    день = день_недели(дт)
    уроки = уроки_на(день, данные)

    обр = f"{имя}, доброе утро. " if имя else "Доброе утро. "

    if not уроки:
        return (обр + f"Сегодня {данные['дни'][день]}, уроков нет. "
                "Можно поспать подольше. Хорошего дня!")

    начало = первое_время(день, данные)
    # перевод времени в «человеческий» вид: 08:30 -> полдевятого
    начало_словами = данные.get("время_словами", {}).get(начало, начало)

    части = [обр + "Пора просыпаться."]
    части.append(f"Сегодня {данные['дни'][день]}, "
                 f"{'один урок' if len(уроки) == 1 else str(len(уроки)) + ' уроков'}, "
                 f"начало в {начало_словами}.")
    части.append("Вставай потихоньку, не торопись.")
    части.append(данные.get("утренняя_добавка", ""))

    return " ".join(x for x in части if x)


def вечер_текст(данные, дт=None, имя=None):
    """Вечернее напоминание: собрать портфель, лечь спать."""
    дт, _ = сейчас() if дт is None else (дт, "")
    имя = имя or данные.get("имя_ребёнка", "")
    обр = f"{имя}, " if имя else ""

    завтра = (день_недели(дт) + 1) % 7
    уроки = уроки_на(завтра, данные)

    if not уроки:
        return (f"{обр}завтра {данные['дни'][завтра]}, уроков нет. "
                "Портфель можно не собирать. Спокойной ночи!")

    предметы = ", ".join(у["предмет"] for у in уроки)
    взять = []
    for у in уроки:
        for в in (у.get("взять") or "").split(","):
            в = в.strip()
            if в and в.lower() not in [x.lower() for x in взять]:
                взять.append(в)

    текст = (f"{обр}пора готовиться ко сну. "
             f"Завтра {данные['дни'][завтра]}, {len(уроки)} уроков: {предметы}. ")
    if взять:
        текст += "Не забудь положить в портфель: " + ", ".join(взять) + ". "
    текст += данные.get("вечерняя_добавка", "Спокойной ночи!")
    return текст


def портфель_текст(данные, дт=None, имя=None):
    """Только список вещей в портфель на завтра."""
    дт, _ = сейчас() if дт is None else (дт, "")
    завтра = (день_недели(дт) + 1) % 7
    уроки = уроки_на(завтра, данные)
    if not уроки:
        return "Завтра уроков нет, портфель не нужен."
    взять = []
    for у in уроки:
        for в in (у.get("взять") or "").split(","):
            в = в.strip()
            if в and в.lower() not in [x.lower() for x in взять]:
                взять.append(в)
    if not взять:
        return "Особых вещей на завтра не задано."
    return "В портфель на завтра: " + ", ".join(взять) + "."


