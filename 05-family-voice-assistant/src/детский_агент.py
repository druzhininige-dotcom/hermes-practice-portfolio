def домашка_текст(данные, дт=None, на_завтра=True):
    """Что задано. Снежана просила: в электронном дневнике не всегда есть."""
    дт, _ = сейчас() if дт is None else (дт, "")
    день = (день_недели(дт) + 1) % 7 if на_завтра else день_недели(дт)
    ключ = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"][день]
    название = данные["дни"][день]

    домашка = (данные.get("домашние_задания") or {}).get(ключ) or {}
    # убираем служебные поля
    домашка = {п: з for п, з in домашка.items() if not п.startswith("_") and з}

    когда = "на завтра" if на_завтра else "на сегодня"

    if not домашка:
        return (f"Домашнее задание {когда} ({название}) пока не записано. "
                f"Скажи, что задали — я запишу.")

    части = [f"Домашка {когда}, {название}:"]
    for предмет, задание in домашка.items():
        части.append(f"{предмет} — {задание}.")
    return " ".join(части)


def записать_домашку(данные, предмет, задание, на_завтра=True, дт=None):
    """Записывает домашнее задание в расписание.json."""
    дт, _ = сейчас() if дт is None else (дт, "")
    день = (день_недели(дт) + 1) % 7 if на_завтра else день_недели(дт)
    ключ = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"][день]

    if "домашние_задания" not in данные:
        данные["домашние_задания"] = {}
    if ключ not in данные["домашние_задания"]:
        данные["домашние_задания"][ключ] = {}

    данные["домашние_задания"][ключ][предмет] = задание

    with open(ФАЙЛ_РАСПИСАНИЯ, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, indent=2)

    return f"Записал: {предмет} — {задание}."


# ─────────────────────────── ОЗВУЧКА ───────────────────────────

def озвучить(текст, голос=ГОЛОС, играть=True, имя_файла=None, настройки=None):
    """Синтез речи edge-tts + проигрывание. Возвращает путь к mp3.

    настройки: {"rate": "-12%", "pitch": "-1Hz"} — мягкость подачи.
    """
    os.makedirs(ПАПКА_ЗВУКА, exist_ok=True)
    if имя_файла is None:
        время = datetime.datetime.now().strftime("%Y%m%d_%H%M%S_%f")
        имя_файла = f"голос_{время}.mp3"
    mp3 = os.path.join(ПАПКА_ЗВУКА, имя_файла)

    команда = ["edge-tts", f"--voice={голос}"]
    if настройки:
        # ОБЯЗАТЕЛЬНО через «=»: значение вида -12% иначе читается как новый флаг
        if настройки.get("rate"):
            команда.append(f"--rate={настройки['rate']}")
        if настройки.get("pitch"):
            команда.append(f"--pitch={настройки['pitch']}")
    команда += ["--text", текст, "--write-media", mp3]

    r = subprocess.run(команда, capture_output=True, timeout=180)
    if r.returncode != 0:
        print("[!] Ошибка синтеза речи:", file=sys.stderr)
        print(r.stderr.decode("utf-8", errors="replace")[:800], file=sys.stderr)
        raise RuntimeError("edge-tts не смог создать голос")

    if not играть:
        return mp3

    # mp3 -> wav, затем winsound (надёжнее всего на Windows)
    wav = mp3[:-4] + ".wav"
    try:
        subprocess.run(
            ["ffmpeg", "-y", "-loglevel", "error", "-i", mp3, wav],
            check=True, capture_output=True, timeout=120
        )
        import winsound
        winsound.PlaySound(wav, winsound.SND_FILENAME)
    except Exception as е:
        # запасной путь: ffplay
        try:
            subprocess.run(["ffplay", "-nodisp", "-autoexit",
                            "-loglevel", "error", mp3], timeout=300)
        except Exception:
            print(f"[!] Не удалось проиграть звук: {е}", file=sys.stderr)
    finally:
        try:
            if os.path.exists(wav):
                os.remove(wav)
        except Exception:
            pass

    return mp3


# ─────────────────────────── CLI ───────────────────────────

def главное():
    if len(sys.argv) < 2:
        print(__doc__)
        return

    команда = sys.argv[1].lower()
    данные = загрузить()

    if команда in ("расписание", "сегодня"):
        д = день_недели()
        текст = расписание_текстом(д, данные)
        print(текст)
        print(f"\n[день: {ДНИ[д]}]")

    elif команда == "завтра":
        д = (день_недели() + 1) % 7
        print(расписание_текстом(д, данные, завтра=True))

    elif команда in ("подъём", "подъем", "будильник"):
        текст = подъём_текст(данные)
        print("🔊", текст)
        озвучить(текст, имя_файла="подъём.mp3", настройки=НАСТРОЙКИ_УТРО)

    elif команда == "вечер":
        текст = вечер_текст(данные)
        print("🔊", текст)
        озвучить(текст, имя_файла="вечер.mp3", настройки=НАСТРОЙКИ_ВЕЧЕР)

    elif команда == "портфель":
        текст = портфель_текст(данные)
        print("🔊", текст)
        озвучить(текст, имя_файла="портфель.mp3", настройки=НАСТРОЙКИ_ВЕЧЕР)

    elif команда == "скажи":
        if len(sys.argv) < 3:
            print("Нужен текст: скажи \"...\"")
            return
        текст = " ".join(sys.argv[2:])
        print("🔊", текст)
        озвучить(текст)

    else:
        print(f"Неизвестная команда: {команда}")
        print(__doc__)


if __name__ == "__main__":
    главное()
