#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
БУДИЛЬНИК: подъём по графику + два звонка-предупреждения.

Логика:
  - читает график_подъёма из расписания.json
  - сам решает, ПОДЪЁМ сейчас или ПРЕДУПРЕЖДЕНИЕ (за N минут)
  - пропускает подъём, если выходной/каникулы (можно отключить)

Запускается по расписанию Windows (см. установить_будильник.py).

Команды:
  python будильник.py              — проверить время и озвучить, если пора
  python будильник.py --тест       — озвучить прямо сейчас (для проверки)
  python будильник.py --статус     — показать график, ничего не говорить
"""
import os
import sys
import json
import subprocess
import datetime

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from детский_агент import (  # noqa: E402
    загрузить, озвучить, подъём_текст, сейчас, день_недели, ГОЛОС
)

ФАЙЛ_СОСТОЯНИЯ = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              "будильник_состояние.json")


def прочитать_состояние():
    try:
        with open(ФАЙЛ_СОСТОЯНИЯ, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


def записать_состояние(с):
    try:
        with open(ФАЙЛ_СОСТОЯНИЯ, "w", encoding="utf-8") as f:
            json.dump(с, f, ensure_ascii=False, indent=2)
    except Exception:
        pass


def время_подъёма(данные, дт):
    """Возвращает (час, минута) подъёма для дня недели."""
    график = данные.get("график_подъёма", {})
    день = день_недели(дт)
    ключ = ["будни", "будни", "будни", "будни", "будни", "суббота", "воскресенье"][день]
    значение = график.get(ключ, "07:00")
    try:
        ч, м = значение.split(":")
        return int(ч), int(м)
    except Exception:
        return 7, 0


def проверить(данные, дт, предупреждение_за=15, тест=False):
    """
    Возвращает (тип, текст):
      ("подъём", текст)   — пора вставать
      ("скоро", текст)    — за N минут
      (None, None)        — не время
    """
    ч, м = время_подъёма(данные, дт)
    цель = дт.replace(hour=ч, minute=м, second=0, microsecond=0)
    разница = (цель - дт).total_seconds() / 60.0  # минут до подъёма

    состояние = прочитать_состояние()
    ключ_дня = дт.strftime("%Y-%m-%d")

    if тест:
        return "подъём", подъём_текст(данные, дт)

    # ±1 минута считается «пора» — чтобы не пропустить при задержке запуска
    if -1 <= разница <= 1:
        if состояние.get("последний_подъём") == ключ_дня:
            return None, None  # уже будили сегодня
        состояние["последний_подъём"] = ключ_дня
        записать_состояние(состояние)
        return "подъём", подъём_текст(данные, дт)

    if предупреждение_за - 1 <= разница <= предупреждение_за + 1:
        if состояние.get("последнее_предупреждение") == ключ_дня:
            return None, None
        имя = данные.get("имя_ребёнка", "")
        обр = f"{имя}, " if имя else ""
        состояние["последнее_предупреждение"] = ключ_дня
        записать_состояние(состояние)
        return "скоро", (f"{обр}через {предупреждение_за} минут подъём. "
                         f"Пора просыпаться, чтобы всё успеть спокойно.")

    return None, None


def главное():
    тест = "--тест" in sys.argv or "--test" in sys.argv
    статус = "--статус" in sys.argv or "--status" in sys.argv

    данные = загрузить()
    дт, день_имя = сейчас()

    if статус:
        ч, м = время_подъёма(данные, дт)
        print(f"Сейчас: {дт.strftime('%Y-%m-%d %H:%M:%S')} ({день_имя})")
        print(f"Подъём по графику: {ч:02d}:{м:02d}")
        print(f"Ребёнок: {данные.get('имя_ребёнка') or '(имя не задано)'}")
        print(f"Смена: {данные.get('смена')}, класс: {данные.get('класс')}")
        return

    тип, текст = проверить(данные, дт, тест=тест)

    if тип is None:
        if тест or статус:
            print("Не время подъёма — молчим.")
        return

    print(f"[{тип}] {текст}")
    озвучить(текст, имя_файла=f"будильник_{тип}.mp3")


if __name__ == "__main__":
    главное()
