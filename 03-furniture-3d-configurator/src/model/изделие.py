# -*- coding: utf-8 -*-
"""
ИЗДЕЛИЕ — параметрическая модель мебели (не «коробка»).

ГЛАВНЫЙ ПРИНЦИП:
  параметры — источник правды, детали — ПРОИЗВОДНАЯ.
  Любая правка (мышкой в 3D или в JSON) пишется в `параметры`, после чего детали
  пересчитываются заново. Детали руками не правятся — иначе дерево разъедется
  с параметрами.

Единицы: миллиметры. Оси: X — ширина, Y — высота, Z — глубина (Z+ вглубь от фасада).

JSON детали (то, что видит раскрой и фабрика):
  id, тип, модуль, материал, размер{d,ш,т}, позиция{x,y,z}, поворот{x,y,z},
  кромка{перед,зад,лево,право,верх,низ}, крепёж[], правило
"""
from __future__ import annotations

import json
import pathlib
from dataclasses import dataclass, field, asdict

import правила as ПР

# ── типы деталей и фасадов (закрытый список, чтобы не разъезжались имена) ──
ТИПЫ_ДЕТАЛЕЙ = {
    "стойка", "полка", "дно", "крыша", "перегородка", "царга", "фасад_корпус",
    "цоколь", "задняя_стенка", "столешница", "бортик", "брусок",
    "ящик_борт", "ящик_дно", "ящик_зад", "фасад_ящика",
    "фасад_распашной", "фасад_стекло", "связь",
}

ТИПЫ_ФАСАДОВ = {"глухой", "распашной", "ящики", "стекло", "витрина", "без_фасада"}

СТОРОНЫ_КРОМКИ = ("перед", "зад", "лево", "право", "верх", "низ")


@dataclass
class Деталь:
    """Один лист (панель), который идёт в раскрой и на фабрику."""
    id: str
    тип: str
    размер: dict                    # {"д": мм, "ш": мм, "т": мм}
    материал: str                   # код из материалы.json
    модуль: str = ""
    позиция: dict = field(default_factory=lambda: {"x": 0.0, "y": 0.0, "z": 0.0})
    поворот: dict = field(default_factory=lambda: {"x": 0.0, "y": 0.0, "z": 0.0})
    кромка: dict = field(default_factory=lambda: {с: None for с in СТОРОНЫ_КРОМКИ})
    крепёж: list = field(default_factory=list)
    правило: str = ""

    # ── производные величины ───────────────────────────────────────────
    @property
    def площадь_м2(self) -> float:
        return self.размер["д"] * self.размер["ш"] / 1e6

    @property
    def периметр_пм(self) -> float:
        return 2 * (self.размер["д"] + self.размер["ш"]) / 1000

    @property
    def кромка_пм(self) -> float:
        """Погонаж кромки = сумма сторон, где кромка реально стоит."""
        д, ш = self.размер["д"], self.размер["ш"]
        длины = {"перед": д, "зад": д, "лево": ш, "право": ш, "верх": ш, "низ": ш}
        return sum(длины[с] for с in СТОРОНЫ_КРОМКИ if self.кромка.get(с)) / 1000

    @property
    def кромка_стороны(self) -> list[str]:
        return [с for с in СТОРОНЫ_КРОМКИ if self.кромка.get(с)]

    def в_json(self) -> dict:
        return asdict(self)


@dataclass
class Секция:
    """Модуль корпуса: то, что клиент называет «секцией», а Костя — «модулем»."""
    модуль: str
    ширина: float
    тип: str = "нижний"              # нижний | верхний | пенал | антресоль
    высота: float = 0.0              # 0 → берётся из правила типа
    глубина: float = 0.0
    фасад: str = "распашной"         # см. ТИПЫ_ФАСАДОВ
    дверей: int = 1
    ящиков: int = 0
    полок: int = 1
    перегородок: int = 0
    полки_высоты: list = field(default_factory=list)  # необязательно: Y полок от дна
    задняя_стенка: bool = True
    цоколь: bool = False
    открытая_ниша: bool = False

    def в_json(self) -> dict:
        return asdict(self)


@dataclass
class Изделие:
    id: str
    название: str = "Изделие"
    тип: str = "шкаф"
    версия: int = 1

    материалы: dict = field(default_factory=lambda: {"корпус": "лдсп16_белый",
                                                      "фасад": "мдф18_эмаль_белая"})
    секции: list = field(default_factory=list)          # [Секция]
    столешница: dict = field(default_factory=lambda: {"есть": False, "материал": "лдсп38_дуб"})
    цоколь: dict = field(default_factory=lambda: {"высота": 100.0, "утопление": 50.0})
    комната: str = ""
    привязка: dict = field(default_factory=lambda: {"x": 0.0, "y": 0.0, "z": 0.0,
                                                    "к_стене": "задняя"})
    узлы: dict = field(default_factory=lambda: {"техника": [], "подсветка": False})
    происхождение: dict = field(default_factory=dict)

    детали: list = field(default_factory=list)          # производная, пересчитывается
    крепёж: list = field(default_factory=list)
    предупреждения: list = field(default_factory=list)

    # ── сериализация ───────────────────────────────────────────────────
    def в_json(self) -> dict:
        return {
            "версия": self.версия,
            "id": self.id,
            "название": self.название,
            "тип": self.тип,
            "происхождение": self.происхождение,
            "габарит": self.габарит(),
            "комната": self.комната,
            "привязка": self.привязка,
            "параметры": {
                "материалы": self.материалы,
                "секции": [с.в_json() for с in self.секции],
                "столешница": self.столешница,
                "цоколь": self.цоколь,
                "узлы": self.узлы,
            },
            "детали": [д.в_json() if isinstance(д, Деталь) else д for д in self.детали],
            "крепёж": self.крепёж,
            "предупреждения": self.предупреждения,
        }

    @staticmethod
    def из_json(данные: dict) -> "Изделие":
        п = данные.get("параметры", {})
        изд = Изделие(
            id=данные.get("id", "изд"),
            название=данные.get("название", "Изделие"),
            тип=данные.get("тип", "шкаф"),
            версия=данные.get("версия", 1),
            материалы=п.get("материалы", {}),
            секции=[Секция(**{k: v for k, v in с.items()}) for с in п.get("секции", [])],
            столешница=п.get("столешница", {"есть": False}),
            цоколь=п.get("цоколь", {"высота": 100.0, "утопление": 50.0}),
            комната=данные.get("комната", ""),
            привязка=данные.get("привязка", {"x": 0.0, "y": 0.0, "z": 0.0}),
            узлы=п.get("узлы", {"техника": [], "подсветка": False}),
            происхождение=данные.get("происхождение", {}),
            крепёж=данные.get("крепёж", []),
            предупреждения=данные.get("предупреждения", []),
        )
        изд.детали = [Деталь(**д) for д in данные.get("детали", [])]
        return изд

    # ── габарит считается из секций, а не задаётся руками ──────────────
    def габарит(self) -> dict:
        if not self.секции:
            return {"ш": 0.0, "в": 0.0, "г": 0.0}
        низ = [с for с in self.секции if с.тип in ("нижний", "пенал")]
        верх = [с for с in self.секции if с.тип in ("верхний", "антресоль")]
        г = max([с.глубина for с in self.секции] or [0.0])
        if низ and верх:
            # двухрядное изделие (кухня): ширина = ширина ряда, а НЕ сумма двух
            # рядов; высота = нижний ряд + столешница (если есть) + верхний ряд
            ш = max(sum(с.ширина for с in низ), sum(с.ширина for с in верх))
            h_низ = max((с.высота for с in низ), default=0.0)
            h_верх = max((с.высота for с in верх), default=0.0)
            стол = ПР.ТОЛЩИНА_СТОЛЕШНИЦЫ if self.столешница.get("есть") else 0.0
            в = h_низ + стол + ПР.значение_расстановки(ПР.ЗАЗОР_ФАРТУК) + h_верх
        else:
            ш = sum(с.ширина for с in self.секции)
            в = max([с.высота for с in self.секции] or [0.0])
        return {"ш": round(ш, 1), "в": round(в, 1), "г": round(г, 1)}

    def найти(self, id_детали: str) -> Деталь | None:
        return next((д for д in self.детали if д.id == id_детали), None)

    def детали_модуля(self, модуль: str) -> list:
        return [д for д in self.детали if д.модуль == модуль]


def сохранить(изд: Изделие, путь) -> pathlib.Path:
    путь = pathlib.Path(путь)
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(json.dumps(изд.в_json(), ensure_ascii=False, indent=1), encoding="utf-8")
    return путь


def загрузить(путь) -> Изделие:
    return Изделие.из_json(json.loads(pathlib.Path(путь).read_text(encoding="utf-8")))
