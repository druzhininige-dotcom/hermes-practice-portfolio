"""
ПОСТРОЕНИЕ ИЗДЕЛИЯ: параметры → детали.

Здесь стоит единственный вход `построить(изделие)`:
  секции → корпус + фасады (+ ящики), столешница, узлы → детали + крепёж.

Все числа — из правила.py; неподтверждённые припуски НЕ применяются и
попадают в изделие.предупреждения со словом УТОЧНИТЬ.
"""
