_HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))
sys.path.insert(0, str(_HERE / "генераторы"))

import правила as ПР                                  # noqa: E402
from изделие import Изделие, Секция, Деталь           # noqa: E402
import генераторы.корпус as Г_корпус                  # noqa: E402
import генераторы.фасады as Г_фасады                  # noqa: E402
import генераторы.ящики as Г_ящики                    # noqa: E402

# высоты по умолчанию — НЕ выдуманы: берутся из правила.py, где помечены УТОЧНИТЬ
ВЫСОТА_ПО_УМОЛЧАНИЮ = {
    "нижний": ПР.значение(ПР.ВЫСОТА_НИЖНЕГО_РЯДА),
    "верхний": ПР.значение(ПР.ВЫСОТА_ВЕРХНЕГО_РЯДА),
    "пенал": 0.0,
    "антресоль": 0.0,
}
ГЛУБИНА_ПО_УМОЛЧАНИЮ = {"нижний": 560.0, "верхний": 300.0, "пенал": 560.0, "антресоль": 300.0}


def построить(изд: Изделие) -> Изделие:
    """Пересчитывает детали изделия из параметров. Возвращает то же изделие."""
    материалы = изд.материалы
    мат_корпус = материалы.get("корпус", "лдсп16_белый")
    мат_фасад = материалы.get("фасад", "мдф18_эмаль_белая")
    мат_задней = материалы.get("задняя_стенка", "двп3_белый")
    мат_дна_ящика = материалы.get("дно_ящика", "двп3_белый")
    мат_столешницы = изд.столешница.get("материал", "лдсп38_дуб")

    зазоры = {
        "полка_сзади": ПР.значение(ПР.ЗАЗОР_ПОЛКИ_СЗАДИ),
        "полка_перед": ПР.значение(ПР.ЗАЗОР_ПОЛКИ_ПЕРЕД),
        "цоколь_высота": ПР.значение(ПР.ЦОКОЛЬ_ВЫСОТА),
        "цоколь_утопление": ПР.значение(ПР.ЦОКОЛЬ_УТОПЛЕНИЕ),
    }

    дет: list[Деталь] = []
    крепёж: list[dict] = []
    предупр: list[str] = []
    узлы = {"техника": list(изд.узлы.get("техника", [])),
            "подсветка": bool(изд.узлы.get("подсветка", False))}

    x_низ = 0.0
    x_верх = 0.0
    y_верхнего = 0.0

    # ── проход 1: привести секции к полным габаритам ────────────────────
    for с in изд.секции:
        if not с.высота:
            с.высота = ВЫСОТА_ПО_УМОЛЧАНИЮ.get(с.тип, 0.0)
            if с.высота:
                предупр.append(f"{с.модуль}: высота взята из правила ({с.высота:.0f} мм, "
                               f"не подтверждена) — УТОЧНИТЬ")
        if not с.глубина:
            с.глубина = ГЛУБИНА_ПО_УМОЛЧАНИЮ.get(с.тип, 0.0)
            предупр.append(f"{с.модуль}: глубина взята по типу секции ({с.глубина:.0f} мм) — УТОЧНИТЬ")

    низ = [с for с in изд.секции if с.тип in ("нижний", "пенал")]
    верх = [с for с in изд.секции if с.тип in ("верхний", "антресоль")]
    h_низ = max((с.высота for с in низ), default=0.0)
    h_верх = max((с.высота for с in верх), default=0.0)
    стол_толщина = ПР.ТОЛЩИНА_СТОЛЕШНИЦЫ if изд.столешница.get("есть") else 0.0
    if низ and верх:
        фартук = ПР.значение_расстановки(ПР.ЗАЗОР_ФАРТУК)
        y_верхнего = h_низ + стол_толщина + фартук
        if not ПР.ЗАЗОР_ФАРТУК[1]:
            предупр.append(f"ЗАЗОР_ФАРТУК = {фартук:.0f} мм — ПРЕДВАРИТЕЛЬНО, ждём Костю")

    # ── проход 2: детали секций ────────────────────────────────────────
    # Секции идут ВСТЫК по накопленной ширине. У кухни два ряда: верхний ряд
    # стоит НАД нижним (по Y) и параллельно ему (по X от 0), а не в линию.
    for с in изд.секции:
        is_верх = с.тип in ("верхний", "антресоль")
        if is_верх:
            base_y = y_верхнего + h_верх - с.высота
            смещение_x = x_верх
            x_верх += с.ширина
        else:
            base_y = 0.0
            смещение_x = x_низ
            x_низ += с.ширина

        д_корпус, п1, _ = Г_корпус.корпус_секции(с, мат_корпус, мат_задней, зазоры)
        _переставить(д_корпус, смещение_x, base_y)
        дет += д_корпус
        предупр += п1
        узлы["цоколь"] = узлы.get("цоколь", 0) + (1 if с.цоколь else 0)

        д_фасад, к_фасад, п2, у2 = Г_фасады.фасады_секции(с, мат_фасад)
        _переставить(д_фасад, смещение_x, base_y)
        дет += д_фасад
        крепёж += к_фасад
        предупр += п2
        for k, v in у2.items():
            узлы[k] = узлы.get(k, 0) + (v if isinstance(v, int) else 1)

        if с.фасад == "ящики":
            д_ящ, к_ящ, п3 = Г_ящики.ящики_секции(с, мат_корпус, мат_фасад, мат_дна_ящика, {})
            _переставить(д_ящ, смещение_x, base_y)
            дет += д_ящ
            крепёж += к_ящ
            предупр += п3

    # ── столешница ────────────────────────────────────────────────────
    if изд.столешница.get("есть"):
        ширина_низа = sum(с.ширина for с in низ)
        глубина = max((с.глубина for с in низ), default=0.0) + ПР.значение(ПР.СВЕС_СТОЛЕШНИЦЫ)
        if ширина_низа and глубина:
            дет.append(Деталь(
                id="столешница.1", тип="столешница", модуль="столешница",
                размер={"д": round(ширина_низа, 1), "ш": round(глубина, 1),
                        "т": ПР.ТОЛЩИНА_СТОЛЕШНИЦЫ},
                материал=мат_столешницы,
                позиция={"x": 0.0, "y": round(h_низ, 1), "z": 0.0},
                кромка={"перед": "пвх2_белая", "лево": "пвх2_белая", "право": "пвх2_белая"},
                правило=f"столешница = ширина низа {ширина_низа:.0f} × (глубина + свес)",
            ))
            if ПР.СВЕС_СТОЛЕШНИЦЫ[1] is False:
                предупр.append("СВЕС_СТОЛЕШНИЦЫ не подтверждён → свес = 0, столешница = глубина корпуса")

    изд.детали = дет
    изд.крепёж = _свести_крепёж(крепёж)
    изд.предупреждения = sorted(set(предупр))
    return изд


def _переставить(детали: list[Деталь], дx: float, дy: float) -> None:
    """Двигает детали модуля в мировые координаты изделия (внутри модуля — локальные)."""
    for д in детали:
        д.позиция = {"x": round(д.позиция["x"] + дx, 1),
                     "y": round(д.позиция["y"] + дy, 1),
                     "z": д.позиция["z"]}


def _свести_крепёж(крепёж: list[dict]) -> list[dict]:
    """Петли/направляющие по всему изделию — одной строкой на тип."""
