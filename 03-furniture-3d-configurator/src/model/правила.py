def значение(правило):
    """Возвращает число правила. Если не подтверждено — 0.0 (не применять)
    и пометку для отчёта."""
    if isinstance(правило, (int, float)):
        return float(правило)
    знач, подтверждено, источник = правило
    return float(знач) if подтверждено else 0.0


def не_подтверждённые() -> list[tuple[str, float, str]]:
    """Список правил, которые ждут числа от Кости: (имя, предложенное, источник)."""
    out = []
    for имя, знач in sorted(globals().items()):
        if имя.startswith("_"):
            continue
        if isinstance(знач, tuple) and len(знач) == 3 and isinstance(знач[1], bool):
            if not знач[1]:
                out.append((имя, float(знач[0]), знач[2]))
    return out


