def значение_расстановки(правило):
    """Значение правила класса «расстановка». Неподтверждённое применяется как
    ПРЕДЛОЖЕННОЕ (не 0) — сцена должна строиться, а не схлопываться."""
    if isinstance(правило, (int, float)):
        return float(правило)
    знач, _, _ = правило
    return float(знач)


