# ── раскрой ЛДСП (гильотина / shelf-packing) ────────────────────────────
def _влезает(длина: float, ширина: float, ш_листа: float, д_листа: float) -> bool:
    """Влезает ли деталь в лист в ОДНОЙ из двух ориентаций.

    ⚠ Здесь была ошибка: сравнивались max/min по отдельности, поэтому деталь
    2722×650 «влезала» в лист 2800×2070 не влезая по факту (2722 > 2070).
    Укладчик эту деталь клал поперёк и деталь выходила за край — лист получал
    заполнение 122 %. Правильная проверка — по ОРИЕНТАЦИЯМ листа.
    Проверка: тесты/проверка_модели.py::тест_листы.
    """
    а, б = max(длина, ширина), min(длина, ширина)
    ориентации = ((ш_листа, д_листа), (д_листа, ш_листа))
    return any(а <= о1 + 1e-9 and б <= о2 + 1e-9 for о1, о2 in ориентации)


def раскладка(детали, ш: float, д: float, пропилы: float) -> tuple[list[dict], list[dict]]:
    """Shelf-packing: полосы идут вдоль стороны «ш», детали кладутся вдоль неё же.

    `детали` = [(длина, ширина, текстура)]. Деталь с текстурой НЕ вращается:
    ложится только в исходной ориентации (длина вдоль «ш», ширина вдоль «д») —
    у ЛДСП с направленной текстурой поворот на 90° ставит волокно поперёк.

    Возвращает (листы, негабарит). Деталь, которая НЕ влезает ни в одной
    ориентации, уходит в `негабарит` и НИКОГДА не попадает в лист: на фабрике
    она просто не выйдет из материала. Молча «обернуть» её через край нельзя.
    """
    негабарит: list[dict] = []
    влезают: list[tuple[float, float, bool]] = []
    for длина, ширина, текстура in детали:
        if текстура:
            влезло = длина <= ш + 1e-9 and ширина <= д + 1e-9
        else:
            влезло = _влезает(длина, ширина, ш, д)
        if влезло:
            влезают.append((длина, ширина, текстура))
        else:
            негабарит.append({"д": max(длина, ширина), "ш": min(длина, ширина)})

    items: list[tuple[float, float]] = []
    for длина, ширина, текстура in влезают:
        if текстура:
            items.append((длина, ширина))
        else:
            items.append(tuple(sorted((длина, ширина), reverse=True)))
    items.sort(key=lambda x: -x[0] * x[1])
    листы: list[dict] = []
    for длина, ширина in items:
        положен = False
        for л in листы:
            for полоса in л["полосы"]:
                if полоса["ш"] + 1e-6 >= ширина and полоса["занято"] + длина + пропилы <= ш:
                    полоса["детали"].append((длина, ширина))
                    полоса["занято"] += длина + пропилы
                    положен = True
                    break
            if положен:
                break
            if л["низ"] + ширина + пропилы <= д:
                л["полосы"].append({"низ": л["низ"], "ш": ширина,
                                    "занято": длина + пропилы, "детали": [(длина, ширина)]})
                л["низ"] += ширина + пропилы
                положен = True
                break
        if not положен:
            листы.append({"низ": ширина + пропилы,
                          "полосы": [{"низ": 0.0, "ш": ширина,
                                      "занято": длина + пропилы, "детали": [(длина, ширина)]}]})
    for i, л in enumerate(листы, 1):
        л["номер"] = i
        л["площадь_детали_м2"] = sum(x * y for п in л["полосы"] for x, y in п["детали"]) / 1e6
        л["заполнение"] = л["площадь_детали_м2"] / (ш * д / 1e6)
    return листы, негабарит


def длина_реза_пм(листы: list[dict], ш: float) -> float:
    """Погонаж распила: полные резы по ширине листа + поперечные резы по полосам."""
    L = 0.0
    for л in листы:
        L += len(л["полосы"]) * ш / 1000.0
        for п in л["полосы"]:
            L += len(п["детали"]) * п["ш"] / 1000.0
    return L


def _пронумеровать(статьи: list[dict]) -> list[dict]:
    """Перенумеровать статьи последовательно 1..N (номера не зашиты в код —
    не бывает дублей вроде двух «10.»)."""
    for i, с in enumerate(статьи, 1):
        имя = с.get("статья", "")
        if ". " in имя:
            имя = имя.split(". ", 1)[1]
        с["статья"] = f"{i}. {имя}"
    return статьи


# ── главная функция ─────────────────────────────────────────────────────
def calculate(изд: Изделие, прайс: dict | None = None,
              материал_листа: str | None = None) -> dict:
    прайс = прайс if прайс is not None else загрузить_прайс()
    материалы = _загрузить_материалы()
    непосчитанное: list[str] = []
    предупр = list(изд.предупреждения)

    # ── 1. группировка деталей для раскроя ──────────────────────────────
    строки: list[dict] = []
    for д in изд.детали:
        m = материалы.get(д.материал, {})
        строки.append({
            "деталь": д.id, "тип": д.тип, "модуль": д.модуль,
            "д": д.размер["д"], "ш": д.размер["ш"], "т": д.размер["т"],
            "материал": д.материал, "название_материала": m.get("название", д.материал),
            "шт": 1,
            "площадь_м2": round(д.площадь_м2, 4),
            "площадь_м2_точно": д.площадь_м2,
            "кромка_пм": round(д.кромка_пм, 3),
            "кромка_пм_точно": д.кромка_пм,
            "кромка_стороны": д.кромка_стороны,
            "позиция": д.позиция, "правило": д.правило,
        })

    свод: dict[str, dict] = {}
    for с in строки:
        к = с["материал"]
        if к not in свод:
            свод[к] = {"материал": к, "название": с["название_материала"],
                       "толщина": с["т"], "штук": 0, "площадь_м2": 0.0, "кромка_пм": 0.0}
        свод[к]["штук"] += с["шт"]
        # площадь материала считается НЕ из округлённой строки, а точно:
        # округление на каждой детали давало расхождение с суммой по деталям
        # (27.743583 против 27.743800 в тесте Т4 — это был реальный дефект).
        свод[к]["площадь_м2"] += с["площадь_м2_точно"]
        свод[к]["кромка_пм"] += с["кромка_пм"]
    по_материалам = [{**v, "площадь_м2_точно": v["площадь_м2"],
                      "площадь_м2": round(v["площадь_м2"], 4),
                      "кромка_пм_точно": v["кромка_пм"],
                      "кромка_пм": round(v["кромка_пм"], 3)}
                     for v in свод.values()]

    # ── 2. корпус: листы ЛДСП ──────────────────────────────────────────
    # лист для раскроя — по выбранному декору корпуса (не ЛИСТ_ПО_УМОЛЧАНИЮ),
    # с фолбэком на аргумент/умолчание. Нет цены у листа → УТОЧНИТЬ (ниже в статьях).
    код_листа = (материал_листа
                 or материалы.get(изд.материалы.get("корпус"), {}).get("лист_код")
                 or ПР.ЛИСТ_ПО_УМОЛЧАНИЮ)
    фонд = материалы.get("__листы", {}).get(код_листа, {})
    if not фонд:
        непосчитанное.append(f"лист ЛДСП «{код_листа}» не описан в материалы.json")
        Ш_Л, Д_Л = 0.0, 0.0
    else:
        # ⚠ РАЗКЛАДКА ИДЁТ ПО МАКСИМУМУ ПЕРВЫМ.
        # pack() укладывает деталь по «ш» (вдоль длинной стороны листа), поэтому
        # ш = БОЛЬШАЯ сторона листа, д = меньшая. Если поменять местами, лист
        # получает заполнение 122 % — деталь «оборачивается» через край.
        # Проверка: тесты/проверка_модели.py::тест_листы (заполнение ≤ 100 %).
        Ш_Л, Д_Л = max(фонд["д"], фонд["ш"]), min(фонд["д"], фонд["ш"])
    # детали, которые режутся из ЛДСП-листа: всё типа «лдсп», КРОМЕ столешниц
    # (столешница — отдельная заготовка 4100×600, она не из листа 2800×2070)
    ТИПЫ_ФАСАДОВ = ("фасад_распашной", "фасад_ящика", "фасад_стекло")
    дет_листов: list[tuple[float, float]] = []
    площадь_лдсп = 0.0
    for д in изд.детали:
        m = материалы.get(д.материал, {})
        # фасады считаются ОТДЕЛЬНОЙ статьёй (фасадные материалы), а не листом
        # корпуса — иначе фасад ЛДСП 18 попадает и в листы корпуса, и в статью
        # фасадов (двойной счёт). Каждая деталь — ровно в одной статье.
        if m.get("тип") == "лдсп" and д.тип != "столешница" and д.тип not in ТИПЫ_ФАСАДОВ:
            текстура = bool(m.get("текстура"))
            дет_листов.append((д.размер["д"], д.размер["ш"], текстура))
            площадь_лдсп += д.площадь_м2
    обрезка = ПР.значение(ПР.ОБРЕЗКА_ЛИСТА)
    if not ПР.ОБРЕЗКА_ЛИСТА[1]:
        непосчитанное.append("ОБРЕЗКА_ЛИСТА не подтверждена → обрезка = 0 (лист целиком) — УТОЧНИТЬ")
    листы, негабарит = раскладка(дет_листов, Ш_Л - 2 * обрезка, Д_Л - 2 * обрезка,
                                  ПР.ПРОПИЛ) if Ш_Л else ([], [])
    распил_пм = длина_реза_пм(листы, Ш_Л) if листы else 0.0

    # ── 2б. негабарит и материал без листа ─────────────────────────────
    if негабарит:
        непосчитанное.append(
            f"{len(негабарит)} деталей длиннее листа {max(Ш_Л, Д_Л):.0f} мм — "
            f"в раскладку не влезли: " +
            ", ".join(f"{н['д']:.0f}×{н['ш']:.0f}" for н in негабарит[:6]))
    # материал, который есть в деталях, но не режется из листа (столешница, стекло)
    группы_листов = {"корпус", "фасад"}
    не_в_лист = {}
    for д in изд.детали:
        m = материалы.get(д.материал, {})
        if m.get("группа") not in группы_листов and д.тип != "столешница":
            не_в_лист.setdefault(m.get("название", д.материал), set()).add(д.тип)
    for название, типы in не_в_лист.items():
        непосчитанное.append(f"материал «{название}» не режется из листа ЛДСП "
                             f"(детали: {', '.join(sorted(типы))}) — считается отдельно: УТОЧНИТЬ")

    # ── 3. кромка корпуса ──────────────────────────────────────────────
    кромка_пм = sum(д.кромка_пм for д in изд.детали)          # по сторонам, точно
    # доля кромления: правило 0.6 подобрано под периметр PRO100, у нас кромка
    # по сторонам. Пока не подтверждено — применяем 1.0 (по сторонам), вариант
    # ×0.6 показываем справочно и пишем предупреждение.
    доля_кромления = ПР.ДОЛЯ_КРОМЛЕНИЯ[0] if ПР.ДОЛЯ_КРОМЛЕНИЯ[1] else 1.0
    прим_кромки = f"периметр деталей {кромка_пм:.2f} п.м"
    if not ПР.ДОЛЯ_КРОМЛЕНИЯ[1]:
        вариант_06 = round(кромка_пм * ПР.ДОЛЯ_КРОМЛЕНИЯ[0], 2)
        прим_кромки += f" (вариант ×{ПР.ДОЛЯ_КРОМЛЕНИЯ[0]:g} = {вариант_06} п.м)"
        непосчитанное.append(f"ДОЛЯ_КРОМЛЕНИЯ {ПР.ДОЛЯ_КРОМЛЕНИЯ[0]:g} не подтверждена → "
                             f"кромка по сторонам ×1.0 (вариант ×{ПР.ДОЛЯ_КРОМЛЕНИЯ[0]:g} = "
                             f"{вариант_06} п.м) — УТОЧНИТЬ у Кости")

    # ── 4. фасады ──────────────────────────────────────────────────────
    фасады = [д for д in изд.детали if д.тип in ("фасад_распашной", "фасад_ящика", "фасад_стекло")]
    фасады_м2 = sum(д.площадь_м2 for д in фасады)
    фасады_пм = sum(д.периметр_пм for д in фасады)
    фасады_кромка_пм = sum(д.кромка_пм for д in фасады)
    фасады_штук = len(фасады)

    # ── 5. столешницы ──────────────────────────────────────────────────
    столешницы = [д for д in изд.детали if д.тип == "столешница"]
    столешница_заготовок = 0
    if столешницы:
        всего_длины = sum(д.размер["д"] for д in столешницы)
        столешница_заготовок = max(1, int(round(всего_длины / 4100.0)))

    # ── 6. фурнитура ───────────────────────────────────────────────────
    петли = sum(к["кол"] for к in изд.крепёж if к["тип"] == "петля_накладная")
    направляющие = sum(к["кол"] for к in изд.крепёж if к["тип"] == "направляющая_500")

    # ── 7. деньги. Каждая цена — из прайса, иначе УТОЧНИТЬ ──────────────
    def строка(название, ключ_прайса, количество, единица, примечание=""):
        ц = цена(прайс, ключ_прайса)
        if ц is None:
            непосчитанное.append(f"{название}: нет цены в прайсе «{ключ_прайса}» — УТОЧНИТЬ")
            return {"статья": название, "кол": round(количество, 3), "ед": единица,
                    "цена": None, "сумма": None, "примечание": примечание + " | УТОЧНИТЬ"}
        return {"статья": название, "кол": round(количество, 3), "ед": единица,
                "цена": ц, "сумма": round(количество * ц, 2), "примечание": примечание}

    лист = материалы.get("__листы", {}).get(код_листа, {})
    статьи = [
        строка(f"1. Корпус — ЛДСП (листы {Ш_Л:.0f}×{Д_Л:.0f})", лист.get("прайс_ключ"),
               len(листы), "лист", f"{площадь_лдсп:.3f} м² деталей, заполнение "
                                   f"{(площадь_лдсп / (len(листы) * Ш_Л * Д_Л / 1e6)) * 100 if листы else 0:.0f} %"),
        строка("2. Кромка 2 мм (материал)", "кромка 2 мм",
               round(кромка_пм * доля_кромления, 2), "пог.м", прим_кромки),
        строка("3. Наклейка кромки 2 мм", "стоимость наклейки кромки 2 мм",
               round(кромка_пм * доля_кромления, 2), "пог.м", "прайс"),
        строка(f"4. Раскрой корпуса (распил ЛДСП 16)", "распил ЛДСП толщиной 10–16 мм",
               round(распил_пм, 2), "пог.м", f"{len(листы)} листов, пропил {ПР.ПРОПИЛ} мм"),
        строка("5. Раскрой фасадных материалов", "Раскрой фасадных материалов",
               round(фасады_пм, 2), "пог.м", f"{фасады_штук} фасадов, {фасады_м2:.3f} м²"),
        строка("6. Наклейка кромки на фасад", "Наклейка кромки на фасад",
               round(фасады_кромка_пм, 2), "пог.м", "по сторонам кромки фасадов"),
        # 7. ФАСАДЫ. Материал фасада в прайсе не имеет строки «ставка покраски» —
        # в генераторе Кости это КОНСТАНТА PAINT_RATE = 15 000 ₽/м² (открытый вопрос
        # проекта: актуальна ли она; PROJECT.md §2). Пока константа не подтверждена —
        # статья помечается УТОЧНИТЬ и НЕ складывается в себестоимость.
        _ставка_фасада(прайс, фасады, материалы),
        строка("8. Фурнитура: петли", "петля накладная", петли, "шт",
               f"{петли} петель: 2 на фасад (правило Кости)"),
        строка("9. Фурнитура: направляющие 500", "направляющая samsung с доводчиком 500 мм",
               направляющие, "пара", f"{направляющие} ящиков"),
    ]
    # 10-я статья: корпус из «Краски (Цвета)» — как тумба под ТВ и детская у Кости.
    # Материал крашеного корпуса идёт по ставке покраски, а не по цене листа ЛДСП.
    крашеные_корпусные_м2 = sum(
        д.площадь_м2 for д in изд.детали
        if материалы.get(д.материал, {}).get("тип") == "эмаль" and д.тип not in
        ("фасад_распашной", "фасад_ящика", "фасад_стекло"))
    if крашеные_корпусные_м2 > 0:
        статьи.append(_ставка_покраски_корпуса(прайс, крашеные_корпусные_м2))
    if столешницы:
        статьи.append(строка(f"Столешница 4100×600×38 ({столешница_заготовок} шт)",
                             "столешница 4100*600*38", столешница_заготовок, "шт",
                             "заготовки = Σдлин / 4100"))

    статьи = _пронумеровать(статьи)

    себестоимость = sum(с["сумма"] for с in статьи if с["сумма"] is not None)
    хватает = all(с["сумма"] is not None for с in статьи)

    return {
        "раскрой": {
            "детали": строки,
            "всего_деталей": len(строки),
            "по_материалам": по_материалам,
            "листы": [{"номер": л["номер"], "деталей": sum(len(п["детали"]) for п in л["полосы"]),
                       "площадь_м2": round(л["площадь_детали_м2"], 3),
                       "заполнение": round(л["заполнение"], 4),
                       "полосы": [{"низ": п["низ"], "высота": п["ш"],
                                   "детали": [{"д": x, "ш": y} for x, y in п["детали"]]}
                                  for п in л["полосы"]]} for л in листы],
            "лист": {"ш": Ш_Л, "д": Д_Л, "код": код_листа},
            "распил_пм": round(распил_пм, 2),
            # ТОЧНОЕ значение (для сверок) + округлённое (для показа).
            # Округлённое до 4 знаков сравнивать с суммой по деталям нельзя:
            # 0.6031 против 0.603136 — это округление, а не ошибка (дефект Т4).
            "площадь_лдсп_м2": площадь_лдсп,
            "площадь_лдсп_м2_показ": round(площадь_лдсп, 4),
            "негабарит": негабарит,
        },
        "смета": {
            "статьи": статьи,
            "себестоимость": round(себестоимость, 2) if хватает else None,
            "наценка": НАЦЕНКА,
            "итого": round(себестоимость * (1 + НАЦЕНКА), 2) if хватает else None,
            "полнота": "полная" if хватает else "НЕПОЛНАЯ — есть статьи без цены",
            "непосчитанное": sorted(set(непосчитанное)),
        },
        "предупреждения": предупр + [п for п in непосчитанное if "УТОЧНИТЬ" in п],
        "источник_цен": "Для ИИ стоимость.xlsx",
    }


def _ставка_фасада(прайс: dict, фасады: list, материалы: dict) -> dict:
    """Статья по фасадам. Цена — ТОЛЬКО из прайса. Строки «покраска фасадов» в прайсе
    нет → статья идёт как УТОЧНИТЬ и не попадает в себестоимость.

    Ставка 15 000 ₽/м² существует в генераторе Кости как КОНСТАНТА
    (PAINT_RATE), открытый вопрос проекта — актуальна ли она (PROJECT.md §2).
    Здесь она НЕ применяется молча: чтобы включить, её надо внести в прайс
    отдельной строкой — тогда статья посчитается сама.
    """
    м2 = round(sum(д.площадь_м2 for д in фасады), 4)
    ц = цена(прайс, "Покраска фасадов МДФ")
    if ц is None:
        return {"статья": f"7. Фасады: покраска МДФ, {len(фасады)} шт", "кол": м2, "ед": "м²",
                "цена": None, "сумма": None,
                "примечание": "нет строки «Покраска фасадов МДФ» в прайсе — УТОЧНИТЬ "
                              "(в генераторе Кости константа 15 000 ₽/м², не подтверждена)"}
    return {"статья": f"7. Фасады: покраска МДФ, {len(фасады)} шт", "кол": м2, "ед": "м²",
            "цена": ц, "сумма": round(м2 * ц, 2), "примечание": "прайс"}


def _ставка_покраски_корпуса(прайс: dict, м2: float) -> dict:
    """Корпус, крашеный в цвет (материал «Цвета» у Кости: тумба под ТВ, детская)."""
    ц = цена(прайс, "Покраска корпуса МДФ")
    if ц is None:
        return {"статья": "10. Корпус крашеный (цвет)", "кол": round(м2, 4), "ед": "м²",
                "цена": None, "сумма": None,
                "примечание": "нет строки «Покраска корпуса МДФ» в прайсе — УТОЧНИТЬ"}
    return {"статья": "10. Корпус крашеный (цвет)", "кол": round(м2, 4), "ед": "м²",
            "цена": ц, "сумма": round(м2 * ц, 2), "примечание": "прайс"}


_МАТЕРИАЛЫ_КЭШ: dict | None = None


def _загрузить_материалы() -> dict:
    """Индекс материалов по КОДУ: {"лдсп16_титан": {...,"группа":"корпус",...}}.

    ⚠ Раньше здесь возвращался сырой json: коды лежат внутри групп
    («корпус», «фасад», «столешница»), поэтому поиск по коду всегда давал None —
    и корпус не попадал в раскрой (0 листов). Теперь индекс строится один раз и
    содержит группу каждого материала. Проверка: тесты/проверка_модели.py::тест_материалы.
    """
    global _МАТЕРИАЛЫ_КЭШ
    if _МАТЕРИАЛЫ_КЭШ is None:
        import json
        сырой = json.loads((_HERE / "материалы.json").read_text(encoding="utf-8"))
        индекс: dict[str, dict] = {}
        for группа in ("корпус", "фасад", "столешница", "кромка"):
            for код, описание in (сырой.get(группа) or {}).items():
                индекс[код] = {**описание, "группа": группа}
        индекс["__листы"] = сырой.get("лист_лдсп", {})
        индекс["__кромки"] = сырой.get("кромка", {})
        _МАТЕРИАЛЫ_КЭШ = индекс
    return _МАТЕРИАЛЫ_КЭШ
