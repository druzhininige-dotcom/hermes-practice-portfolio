# ── факты из прогонов ──────────────────────────────────────────────────────
def latest(pattern: str) -> Path:
    files = sorted(DATA.glob(pattern), key=lambda p: p.stat().st_mtime, reverse=True)
    if not files:
        raise SystemExit(f"нет файла {pattern} — сначала прогоните скрипт калибровки")
    return files[0]


def calibration_facts() -> dict:
    path = latest("calibration_*.csv")
    rows = list(csv.DictReader(path.open(encoding="utf-8-sig"), delimiter=";"))
    total = len(rows)
    ok = sum(1 for r in rows if r["итог"] == "OK")
    leads = sum(1 for r in rows if r["ожидание"] == "лид")
    negatives = total - leads
    cross = [r for r in rows if r["факт_второй"] not in ("—", "")]
    facts = {
        "файл": path.name,
        "всего": total,
        "совпало": ok,
        "лиды": leads,
        "не_лиды": negatives,
        "перекрёстных_с_двумя_профилями": len(cross),
        "контрольные": [
            {"кейс": r["id"], "балл": r["факт_балл"], "профиль": r["факт_профиль"],
             "второй": r["факт_второй"]} for r in rows
        ],
    }
    conn = sqlite3.connect(DATA / "calibrate.db")
    cost, calls = conn.execute("SELECT ROUND(SUM(cost_usd), 6), COUNT(*) FROM llm_calls").fetchone()
    conn.close()
    facts["расход_калибровки"] = cost or 0.0
    facts["вызовов_калибровки"] = calls or 0
    return facts


def num_score(v: float) -> str:
    v = round(float(v), 1)
    return str(int(v)) if v == int(v) else f"{v:.1f}".replace(".", ",")


def stability_facts() -> dict:
    path = latest("stability_*.json")
    d = json.loads(path.read_text(encoding="utf-8"))
    lines = []
    for case_id, runs in d["cases"].items():
        best = runs[0]["best"]
        score = runs[0]["score"]
        sec = runs[0]["secondary"]
        same = len({(r["best"], r["score"], tuple(s["slug"] for s in r["secondary"]))
                    for r in runs}) == 1
        lines.append({
            "кейс": case_id,
            "прогонов": len(runs),
            "совпало": len(runs) if same else sum(
                1 for r in runs
                if (r["best"], r["score"], tuple(s["slug"] for s in r["secondary"]))
                == (best, score, tuple(s["slug"] for s in sec))),
            "профиль": best,
            "балл": score,
            "второй": ", ".join(f"{s['slug']} {num_score(s['score'])}" for s in sec) or "нет",
        })
    return {"файл": path.name, "модель": d["model"], "промт": d["prompt_fingerprint"],
            "стабильно": d["stable"], "расход": d["cost_usd"], "строки": lines}


def fmt_stab(row: dict) -> str:
    """«cross_ai_mp: ai 9, второго профиля нет, 3 из 3» — числа с запятой."""
    second_txt = (f"второй: {row['второй']}" if row["второй"] != "нет"
                  else "второго профиля нет")
    return (f"{row['кейс']}: {row['профиль']} {num_score(row['балл'])}, "
            f"{second_txt}, {row['совпало']} из {row['прогонов']}")


def pytest_facts() -> int:
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "-q"], cwd=BASE,
        capture_output=True, text=True, encoding="utf-8", errors="ignore",
    )
    out = (proc.stdout or "") + (proc.stderr or "")
    m = re.search(r"(\d+) passed", out)
    if not m:
        raise SystemExit("pytest не дал числа passed:\n" + out[-1500:])
    if proc.returncode != 0:
        raise SystemExit("pytest упал, отчёт не собираю:\n" + out[-1500:])
    return int(m.group(1))


def case_set_facts() -> dict:
    cases = yaml.safe_load((BASE / "tests" / "cases.yaml").read_text(encoding="utf-8"))
    # перекрёстные кейсы помечены префиксом id cross_ (один из них ожидает только
    # профиль ai: второй профиль там как раз не должен появляться)
    cross = [c for c in cases if str(c["id"]).startswith("cross_")]
    return {"всего": len(cases), "базовых": len(cases) - len(cross), "перекрёстных": len(cross)}


# ── оформление docx ────────────────────────────────────────────────────────
def para(doc, text: str, bold: bool = False, italic: bool = False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.italic = italic
    return p


def bullets(doc, items: list[str]) -> None:
    for it in items:
        doc.add_paragraph(it, style="List Bullet")


def table(doc, headers: list[str], rows: list[list[str]], widths: list[float] | None = None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        run.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = str(value)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    return t


def mono(doc, text: str, size: int = 10):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.name = "Consolas"
    r.font.size = Pt(size)
    return p


